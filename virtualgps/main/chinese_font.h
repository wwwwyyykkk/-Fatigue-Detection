static inline const uint8_t* chinese_font_lookup(uint16_t gb_code) {
    int lo = 0, hi = CHINESE_FONT_COUNT - 1;
    while (lo <= hi) {
        int mid = (lo + hi) / 2;
        if (chinese_font_table[mid].gb == gb_code)
            return chinese_font_table[mid].data;
        if (gb_code < chinese_font_table[mid].gb)
            hi = mid - 1;
        else
            lo = mid + 1;
    }
    return NULL;
}